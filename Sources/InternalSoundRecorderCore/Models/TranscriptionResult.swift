import Foundation

public struct TranscriptSegment: Identifiable, Codable, Sendable {
    public var id: UUID = UUID()
    public let timestamp: TimeInterval
    public let duration: TimeInterval
    public let text: String

    public init(timestamp: TimeInterval, duration: TimeInterval, text: String) {
        self.timestamp = timestamp
        self.duration = duration
        self.text = text
    }

    public var formattedTimestamp: String {
        let totalSeconds = Int(timestamp)
        let hours = totalSeconds / 3600
        let minutes = (totalSeconds % 3600) / 60
        let seconds = totalSeconds % 60
        if hours > 0 {
            return String(format: "%02d:%02d:%02d", hours, minutes, seconds)
        } else {
            return String(format: "%02d:%02d", minutes, seconds)
        }
    }
}

public struct TranscriptionResult: Sendable {
    public let fullText: String
    public let segments: [TranscriptSegment]

    public init(fullText: String, segments: [TranscriptSegment]) {
        self.fullText = fullText
        self.segments = segments
    }

    /// Generates standard SubRip (.srt) subtitle format
    public var srtFormat: String {
        var srt = ""
        for (index, segment) in segments.enumerated() {
            let start = formatSRTTime(segment.timestamp)
            let end = formatSRTTime(segment.timestamp + segment.duration)
            srt += "\(index + 1)\n"
            srt += "\(start) --> \(end)\n"
            srt += "\(segment.text)\n\n"
        }
        return srt
    }

    /// Generates structured Markdown meeting notes with markers and transcript
    public func markdownMeetingNotes(recordingName: String, markers: [MarkerItem] = []) -> String {
        var md = "# Meeting Notes — \(recordingName)\n\n"
        md += "**Generated by**: MacAudioRecorder (On-Device AI)\n"
        md += "**Date**: \(Date().formatted())\n\n"

        if !markers.isEmpty {
            md += "## 📍 Key Discussion Markers\n\n"
            for m in markers {
                md += "- **[\(m.formattedTimestamp)]** \(m.label)\n"
            }
            md += "\n---\n\n"
        }

        md += "## 📝 Full Transcript\n\n"
        if segments.isEmpty {
            md += "\(fullText)\n"
        } else {
            for s in segments {
                md += "> **[\(s.formattedTimestamp)]** \(s.text)\n\n"
            }
        }

        return md
    }

    private func formatSRTTime(_ time: TimeInterval) -> String {
        let totalSeconds = Int(time)
        let hours = totalSeconds / 3600
        let minutes = (totalSeconds % 3600) / 60
        let seconds = totalSeconds % 60
        let millis = Int((time.truncatingRemainder(dividingBy: 1.0)) * 1000)
        return String(format: "%02d:%02d:%02d,%03d", hours, minutes, seconds, millis)
    }
}
